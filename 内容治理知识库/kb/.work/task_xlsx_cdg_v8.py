# ── G6：必须做段落编号整体重排，避免重复 ─────────────────────────────
def _renumber_must(text):
    i = text.index("必须做")
    head, tail = text[:i+3], text[i+3:]
    lines = tail.split("\n")
    n = 0
    out = []
    for ln in lines:
        if re.match(r'^\s*\d+[.、]', ln):
            n += 1
            out.append(re.sub(r'^(\s*)\d+([.、])', lambda m: f"{m.group(1)}{n}{m.group(2)}", ln))
        else:
            out.append(ln)
    return head + "\n".join(out)

