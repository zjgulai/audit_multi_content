"""案例层「题材一致性」闸门 —— **独立可导入的单一实现**。

## 为什么单独成件（而不是内联在 review.py 里）

`kb/l7/skills/kb-content-review/scripts/review.py` **在 import 时就会把整条评审引擎跑起来**
（模块级解析 `sys.argv` 并执行），所以**测不了** —— 想给它写判据自证，只能把要测的逻辑
抽到一个能被 import 的模块里。这件的存在理由就是这个：**一份实现，两边共用**
（`review.py` 调它、`kb/l8/check_case_thematic_gate.py` 测它），而不是测试去测一份副本。

## 病灶（2026-10-14 实测）

D8 奶瓶清洗机视频（`MC-US-YT-9-vZmvgIrRA`）与 BM04 **婴儿监控器**视频
（`MC-US-YT-iAVRpPXgAeU`），两份素材原文里**一个「水槽 / 奶瓶 / 配件 / 堆满」都没有**，
却被同一条反例条款「【品牌一致性】…水槽、奶瓶、配件不要堆得过满，避免画面杂乱」
当了**依据**。报告自己把这件事写在 `reason` 里：

> 库内反例条款 S-1.296（品牌一致性）按**同源/同题材**引证 —— 该案例记录的原文
> （含评审反馈）是库内留痕，**不是本素材里的字**；本单据此给 REVIEW，需人工点开 L0 核对是否真同源

⇒ 那不是「同题材」，是**按分类标签（品牌一致性）套条款**：BM25 命中一条案例单元，
案例就被当成本素材的依据，而两者主题毫无交集。

## ★★ 2026-10-14 第二轮：**第一版是空转的**（我自己造的，记在这里别重犯）

第一版签名是 `case_thematic_ok(clause, material_text, hit_text="")`，调用点传的是
`row["text_excerpt"]`。而 `text_excerpt` 来自 **BM25 的库内单元**（`kb/l6/retriever.py:397`
→ `d["text_excerpt"]`），**对案例条款而言那就是条款自己的话** ⇒
`hay = 素材 + 条款自己` ⇒ 主题词**必然命中**。

实测（S-1.296 对 D8 清洗机视频）：条款 36 个主题词在**它自己的单元文本**里
**36/36 全中** ⇒ 闸门**恒过**，等于没装。

**为什么自证没抓到**：`check_case_thematic_gate.py` 调的是 **2 参**形式（正确写法），
而**调用点是 3 参** —— 我测了纯函数，**从没测接线**。
⇒ 现在**参数直接删掉**（留着还能再被误用），并给自证加一条**接线反向对照**（E 组）。

## 本闸门只回答一件事

**这条案例条款讲的事，本素材里到底有没有？**
—— 只看**素材**，不看条款自己。（条款自己当然"包含"自己，那不是证据。）

## 边界（照实说）

1. **只取中文主题词** ⇒ 英文/中英混排素材上，原本靠通用词命中的案例依据会被挡掉。
   **那是有意的** —— 那种命中本来就不成立。
2. **同源一路不在本件**：`review.py` 已按 `resource_id` 单独处理「素材就是那条案例」的情形。
3. **只挡「产出依据」，不动覆盖判据** —— 覆盖问的是「库认不认识这个题材」，
   案例留痕仍可作覆盖证据。改覆盖会动到 PASS/拒答的门，那是另一件事、另需报批。
"""

import re

# ── 通用词表：这些词在几乎每一条反例里都出现，**不构成题材一致性的证据** ──────────
# 实测来源：把 239 条反例条款批量取中文词做频次，手工挑出「跨题材都出现」的那批。
CASE_GENERIC_TERMS = frozenset("""
视频 图片 文案 画面 场景 要求 使用 项目 海报 审核 终审 初审 复审 问题 要点 原因 建议
注意 整体 内容 设计 品牌 统一 调整 修改 需要 不要 可以 如果 这个 那个 我们 你们 他们
辛苦 麻烦 看看 以下 如下 此外 另外 同时 以及 并且 但是 因为 所以 然后 目前 请问 帮忙
谢谢 反馈 素材 版本 尺寸 参考 保持 体现 呈现 显示 出现 位置 区域 左侧 右侧 上方 下方
中间 中央 大小 颜色 字体 文字 排版 元素 效果 感觉 风格 调性 不符合 符合 习惯 用户
""".split())


def case_subject_terms(clause):
    """取条款的**主题词**：中文 2–6 字、去通用词。返回 `set`。"""
    src = str((clause or {}).get("reason_analysis") or "") + " " + \
          str((clause or {}).get("sample_body") or "")
    toks = re.findall(r"[\u4e00-\u9fff]{2,6}", src)
    return {t for t in toks if t not in CASE_GENERIC_TERMS}


def case_thematic_ok(clause, material_text):
    """案例条款能不能当**本素材的依据**。返回 `(bool, 理由)`。

    **只判题材对不对口，不动任何门限、不改覆盖判据。**

    ★ 只有两个参数，**这是有意的**（2026-10-14 第二轮）：第三个参数一旦存在，
      调用方就会顺手把「库内单元自己的文本」传进来 ⇒ 闸门恒过。
      见文件头「第一版是空转的」。**不要为方便再加回第三个参数。**
    """
    terms = case_subject_terms(clause)
    if not terms:
        return False, "条款无主题词（保守不认）"
    hay = str(material_text or "")
    hit = sorted(t for t in terms if t in hay)
    if hit:
        return True, "主题词命中：" + "、".join(hit[:5])
    return False, "主题词零命中（题材不对口）"
